"""Generate reviewable PostgreSQL DDL from current ORM metadata, without accessing a database."""

from __future__ import annotations

import argparse
from importlib import import_module
from pathlib import Path
import re

from sqlalchemy import JSON, Enum, MetaData
from sqlalchemy.dialects.postgresql import JSONB, dialect
from sqlalchemy.dialects.postgresql.named_types import CreateEnumType
from sqlalchemy.schema import CreateIndex, CreateTable
from supreme_common.database import prepare_metadata
from supreme_common.postgres_journal import metadata as event_metadata
from supreme_common.supabase_database import SERVICE_SCHEMAS

ROOT = Path(__file__).resolve().parents[1]
DESTINATION = ROOT / "supabase/schema.sql"
EXTRA_SCHEMAS = ("nfse", "nfe", "tax_audit", "events")


def domain_metadata() -> dict[str, MetaData]:
    result = {}
    for service, schema in SERVICE_SCHEMAS.items():
        package = service.replace("-", "_")
        import_module(package + ".app")  # Includes integration models, IAM users and Pluggy/BPO.
        # ORM modules must be loaded even when the app module does not import them yet.
        for module_name in (package + ".models", package + ".events"):
            try:
                import_module(module_name)
            except ModuleNotFoundError as exc:
                if exc.name != module_name:
                    raise
        base = import_module(package + ".database").Base
        prepare_metadata(base, service)
        target = MetaData()
        for table in base.metadata.sorted_tables:
            copied = table.to_metadata(target, schema=schema)
            # Copied constraints come from a set. Stabilize DDL across Python processes.
            for order, constraint in enumerate(
                sorted(
                    copied.constraints,
                    key=lambda item: (
                        type(item).__name__,
                        str(item.name or ""),
                        tuple(item.columns.keys()),
                    ),
                )
            ):
                constraint._creation_order = order
            for column in copied.columns:
                if isinstance(column.type, JSON):
                    column.type = JSONB()
        result[schema] = target
    result["events"] = event_metadata
    return result


def generate_sql() -> str:
    sql = ["-- Generated by python -m scripts.supabase_schema. Initial schema; no data migration.", "BEGIN;"]
    schemas = [*SERVICE_SCHEMAS.values(), *EXTRA_SCHEMAS]
    for schema in schemas:
        role = "supreme_" + schema
        sql += [
            f"CREATE SCHEMA IF NOT EXISTS {schema};",
            f"REVOKE ALL ON SCHEMA {schema} FROM PUBLIC, anon, authenticated;",
            f"DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '{role}') THEN "
            f"CREATE ROLE {role} NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS; "
            "END IF; END $$;",
            f"GRANT USAGE ON SCHEMA {schema} TO {role};",
            f"ALTER DEFAULT PRIVILEGES IN SCHEMA {schema} REVOKE ALL ON TABLES FROM PUBLIC, anon, authenticated;",
        ]
    for schema, metadata in domain_metadata().items():
        enums = {}
        for table in metadata.tables.values():
            for column in table.columns:
                if isinstance(column.type, Enum) and column.type.native_enum:
                    enum = column.type.dialect_impl(dialect())
                    enums[enum.name] = enum
        for enum in sorted(enums.values(), key=lambda enum: enum.name):
            ddl = str(CreateEnumType(enum).compile(dialect=dialect()))
            sql.append(f"DO $$ BEGIN {ddl}; EXCEPTION WHEN duplicate_object THEN NULL; END $$;")
        for table in metadata.sorted_tables:
            sql.append(str(CreateTable(table, if_not_exists=True).compile(dialect=dialect())).strip() + ";")
            for index in sorted(table.indexes, key=lambda index: index.name):
                sql.append(str(CreateIndex(index, if_not_exists=True).compile(dialect=dialect())) + ";")
    sql.append((ROOT / "supabase/fiscal_metadata.sql").read_text(encoding="utf-8"))
    for table in fiscal_tables():
        sql.append(str(CreateTable(table, if_not_exists=True).compile(dialect=dialect())).strip() + ';')
    for schema in schemas:
        role = "supreme_" + schema
        sql += [
            f"REVOKE ALL ON ALL TABLES IN SCHEMA {schema} FROM PUBLIC, anon, authenticated;",
            f"REVOKE ALL ON ALL SEQUENCES IN SCHEMA {schema} FROM PUBLIC, anon, authenticated;",
            f"GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA {schema} TO {role};",
            f"GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA {schema} TO {role};",
            # No policy for browser roles. Tenant checks remain in Supreme's authenticated backend.
            f"DO $$ DECLARE t record; BEGIN FOR t IN SELECT tablename FROM pg_tables WHERE schemaname = '{schema}' LOOP "
            "EXECUTE format('ALTER TABLE %I.%I ENABLE ROW LEVEL SECURITY', "
            f"'{schema}', t.tablename); "
            "EXECUTE format('DROP POLICY IF EXISTS supreme_backend ON %I.%I', "
            f"'{schema}', t.tablename); "
            "EXECUTE format('CREATE POLICY supreme_backend ON %I.%I TO %I USING (true) WITH CHECK (true)', "
            f"'{schema}', t.tablename, '{role}'); END LOOP; END $$;",
        ]
    sql += [
        "CREATE OR REPLACE FUNCTION iam.prevent_audit_log_mutation() RETURNS trigger LANGUAGE plpgsql "
        "SET search_path = pg_catalog AS $$ BEGIN RAISE EXCEPTION 'Audit logs are append-only.'; END; $$;",
        "REVOKE ALL ON FUNCTION iam.prevent_audit_log_mutation() FROM PUBLIC, anon, authenticated;",
        "DROP TRIGGER IF EXISTS trg_audit_logs_immutable ON iam.audit_logs;",
        "CREATE TRIGGER trg_audit_logs_immutable BEFORE UPDATE OR DELETE ON iam.audit_logs "
        "FOR EACH ROW EXECUTE FUNCTION iam.prevent_audit_log_mutation();",
        "REVOKE UPDATE, DELETE ON iam.audit_logs FROM supreme_iam;",
        "REVOKE UPDATE, DELETE ON events.events, events.deliveries FROM supreme_events;",
        "COMMIT;",
    ]
    return "\n".join(line.rstrip() for line in "\n\n".join(sql).splitlines()) + "\n"


def fiscal_tables():
    from svc_nfse_engine.repository import metadata as nfse_metadata
    from svc_federal_tax_audit.repository import files, outbox as audit_outbox
    from svc_nfe_difal.repository import outbox as nfe_outbox
    return [*nfse_metadata.sorted_tables, files, audit_outbox, nfe_outbox]


def migration_paths() -> list[Path]:
    return sorted((ROOT / 'supabase' / 'migrations').glob('*.sql'))


def _split_sql_list(body: str) -> list[str]:
    parts, current, depth = [], [], 0
    for char in body:
        if char == '(':
            depth += 1
        elif char == ')':
            depth -= 1
        if char == ',' and depth == 0:
            parts.append(''.join(current).strip())
            current = []
        else:
            current.append(char)
    tail = ''.join(current).strip()
    if tail:
        parts.append(tail)
    return parts


def _column_type(definition: str) -> str | None:
    tightened = re.sub(r'\([^)]*\)', lambda match: re.sub(r'\s+', '', match.group(0)), definition)
    tokens = tightened.split()
    if not tokens:
        return None
    name = tokens[0].upper()
    if name in {'CONSTRAINT', 'PRIMARY', 'UNIQUE', 'CHECK', 'FOREIGN'}:
        return None
    stop = {'NOT', 'NULL', 'DEFAULT', 'PRIMARY', 'UNIQUE', 'REFERENCES', 'CONSTRAINT', 'CHECK', 'COLLATE'}
    kind = []
    for token in tokens[1:]:
        if token.upper() in stop:
            break
        kind.append(token)
    return ' '.join(kind)


def applied_migration_tables() -> dict[str, dict[str, str]]:
    """First CREATE TABLE wins, matching PostgreSQL IF NOT EXISTS."""
    pattern = re.compile(
        r'CREATE TABLE IF NOT EXISTS\s+([a-z_][a-z0-9_]*)\.([a-z_][a-z0-9_]*)\s*\((.*?)\)\s*;',
        re.IGNORECASE | re.DOTALL,
    )
    tables: dict[str, dict[str, str]] = {}
    for path in migration_paths():
        sql = re.sub(r'--.*?$', '', path.read_text(encoding='utf-8'), flags=re.MULTILINE)
        for schema, name, body in pattern.findall(sql):
            key = f'{schema}.{name}'
            if key in tables:
                continue
            columns = {}
            for definition in _split_sql_list(body):
                kind = _column_type(definition)
                if kind:
                    columns[definition.split()[0].strip('"')] = kind
            tables[key] = columns
    return tables


def runtime_tables():
    tables = [table for metadata in domain_metadata().values() for table in metadata.tables.values()]
    from svc_federal_tax_audit.repository import snapshots
    from svc_nfe_difal.repository import catalog, sessions
    return [*tables, *fiscal_tables(), catalog, sessions, snapshots]


def _family(type_name: str) -> str:
    kind = type_name.upper()
    if 'JSON' in kind:
        return 'json'
    if kind.startswith('BOOL'):
        return 'bool'
    if 'UUID' in kind:
        return 'uuid'
    if 'TIME' in kind or kind == 'DATE' or kind.startswith('DATE'):
        return 'datetime'
    if 'INT' in kind or 'SERIAL' in kind:
        return 'int'
    if kind.startswith(('NUMERIC', 'DECIMAL', 'DOUBLE', 'REAL', 'FLOAT')):
        return 'number'
    if kind.startswith(('VARCHAR', 'CHAR', 'TEXT', 'STRING', 'CHARACTER')):
        return 'string'
    return 'other'


def _model_family(column_type) -> str:
    if type(column_type).__name__ == 'Variant':
        column_type = column_type.impl
    name = type(column_type).__name__.upper()
    if 'JSON' in name:
        return 'json'
    if 'BOOL' in name:
        return 'bool'
    if 'UUID' in name:
        return 'uuid'
    if 'DATE' in name or 'TIME' in name:
        return 'datetime'
    if 'INT' in name:
        return 'int'
    if any(token in name for token in ('NUMERIC', 'FLOAT', 'DECIMAL', 'DOUBLE')):
        return 'number'
    if any(token in name for token in ('CHAR', 'STRING', 'TEXT', 'ENUM')):
        return 'string'
    return 'other'


def migration_gaps() -> list[str]:
    """Model columns that the ordered migration files do not create."""
    applied = applied_migration_tables()
    gaps, seen = [], set()
    for table in runtime_tables():
        key = f'{table.schema}.{table.name}'
        if key in seen:
            continue
        seen.add(key)
        remote = applied.get(key)
        if remote is None:
            gaps.append(key)
            continue
        for column in table.columns:
            sql_type = remote.get(column.name)
            if sql_type is None:
                gaps.append(f'{key}.{column.name}')
                continue
            expected, actual = _model_family(column.type), _family(sql_type)
            if expected != actual and not (expected == 'string' and actual == 'other'):
                gaps.append(f'{key}.{column.name}:{sql_type}')
    return gaps


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Compara a migração com os modelos, sem gravar.")
    args = parser.parse_args()
    sql = generate_sql()
    gaps = migration_gaps()
    if args.check:
        if not DESTINATION.exists() or DESTINATION.read_text(encoding="utf-8") != sql:
            raise SystemExit(
                "Migração divergente dos modelos. Prepare e revise uma migração antes de implantar."
            )
        if gaps:
            raise SystemExit('A sequência de migrações não cobre os modelos atuais: ' + ', '.join(gaps[:30]))
        print("Migração Supabase compatível com os modelos atuais.")
    else:
        DESTINATION.parent.mkdir(parents=True, exist_ok=True)
        DESTINATION.write_text(sql, encoding="utf-8")
        print("SQL gerado em " + str(DESTINATION.relative_to(ROOT)))


if __name__ == "__main__":
    main()
